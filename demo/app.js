  /* ---------------- tamper-evident audit (demo hash, FNV-1a 64-bit style) ---------------- */
  function fnv(str) {
    let h1 = 0x811c9dc5, h2 = 0x01000193;
    for (let i = 0; i < str.length; i++) {
      const c = str.charCodeAt(i);
      h1 = Math.imul(h1 ^ c, 16777619) >>> 0;
      h2 = Math.imul(h2 ^ (c + i), 2246822519) >>> 0;
    }
    return (h1.toString(16).padStart(8, '0') + h2.toString(16).padStart(8, '0'));
  }
  function now() {
    const d = new Date();
    return d.toTimeString().slice(0, 8);
  }
  function audit(actor, kind, msg) {
    const prev = S.audit.length ? S.audit[S.audit.length - 1].hash : '0'.repeat(16);
    const ts = now();
    const hash = fnv(prev + ts + actor + kind + msg);
    S.audit.push({ ts, actor, kind, msg, hash, prev });
    if (S.view === 'approvals') renderApprovals();
  }

