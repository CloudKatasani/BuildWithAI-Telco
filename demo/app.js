  /* ---------------- run engine ---------------- */
  function newRun(plane) {
    const sc = plane === 'build' ? DC.BUILD_SCENARIOS.find((s) => s.id === S.sel.build) : DC.OPERATE_SCENARIOS.find((s) => s.id === S.sel.operate);
    const steps = plane === 'build' ? buildSteps(sc) : operateSteps(sc);
    stopRun(plane);
    S.runs[plane] = { id: plane[0].toUpperCase() + '-' + (++S.seq), plane, sc, steps, i: 0, li: 0, log: [], arts: [], status: 'running', timer: null, started: Date.now(), gatesDone: 0, waitingFor: null, revisions: 0 };
    log(plane, 'sys', 'Runtime', `Run ${S.runs[plane].id} started: ${sc.name}`);
    audit('Runtime', 'run.start', `${plane} ${S.runs[plane].id} ${sc.name}`);
    tick(plane);
    rerender();
  }
  function stopRun(plane) {
    const r = S.runs[plane];
    if (r && r.timer) clearTimeout(r.timer);
  }
  function log(plane, kind, who, msg) {
    const r = S.runs[plane];
    if (!r) return;
    r.log.push({ t: now(), kind, who, msg });
    const con = document.getElementById('console-' + plane);
    if (con && S.view === plane) {
      if (con.querySelector('.empty')) con.innerHTML = '';
      con.insertAdjacentHTML('beforeend', lineHTML(r.log[r.log.length - 1]));
      con.scrollTop = con.scrollHeight;
    }
  }
  function lineHTML(l) {
    const cls = l.kind === 'gate' ? 'gate' : l.kind === 'ok' ? 'ok' : l.kind === 'bad' ? 'bad' : '';
    const whoCls = l.kind === 'human' || l.kind === 'ok' || l.kind === 'bad' ? 'h' : l.kind === 'sys' || l.kind === 'gate' ? 'sys' : '';
    return `<div class="ln ${cls}"><span class="t">${esc(l.t)}</span><span class="who ${whoCls}">${esc(l.who)}</span><span class="msg">${esc(l.msg)}</span></div>`;
  }
  function tick(plane) {
    const r = S.runs[plane];
    if (!r || r.status !== 'running') return;
    const step = r.steps[r.i];
    if (!step) { finishRun(plane); return; }
    if (r.li < step.lines.length) {
      log(plane, 'agent', step.agent, step.lines[r.li]);
      r.li++;
      r.timer = setTimeout(() => tick(plane), 420 / S.speed);
      if (S.view === plane) renderStages(plane);
      return;
    }
    if (step.gov && !step._govDone) { step._govDone = true; log(plane, 'agent', 'Governance & Lineage', step.gov.replace('Governance & Lineage: ', '')); r.timer = setTimeout(() => tick(plane), 420 / S.speed); return; }
    if (step.art && !step._artDone) {
      step._artDone = true;
      (Array.isArray(step.art) ? step.art : [step.art]).forEach((a) => r.arts.push(Object.assign({ by: step.agent }, a)));
      if (S.view === plane) renderArtifacts(plane);
    }
    if (step.gate && !step._gateDone) {
      raiseGate(plane, step);
      return;
    }
    r.i++; r.li = 0;
    r.timer = setTimeout(() => tick(plane), 300 / S.speed);
    if (S.view === plane) renderStages(plane);
  }

  function gateSpec(plane, step, r) {
    if (plane === 'build') {
      const g = DC.BUILD_GATES[step.gate];
      return { gate: step.gate, title: `${step.gate} · ${g.name}`, approvers: g.approvers.slice(), checks: g.check, cls: step.gate === 'G7' || step.gate === 'G9' ? 'A3' : 'A1' };
    }
    const sc = r.sc;
    if (step.gate === 'ACT') {
      const roles = [...new Set(sc.actions.flatMap((a) => a.approvers))];
      return { gate: 'ACT', title: 'Approve action plan', approvers: roles, checks: ['Blast radius stated per action', 'Rollback defined per action', 'Verification check defined', 'Change record linked for A3'], cls: sc.actions.some((a) => a.cls === 'A3') ? 'A3' : 'A2' };
    }
    if (step.gate === 'COMMS') return { gate: 'COMMS', title: 'Approve stakeholder message', approvers: sc.commsApprovers.slice(), checks: ['Facts match incident timeline', 'No speculation on cause', 'Plain language'], cls: 'A3' };
    return { gate: 'KEDB', title: 'Approve known-error entry', approvers: ['PRB'], checks: ['Root cause evidenced', 'Pre-check is read-only', 'Linked to incident'], cls: 'A1' };
  }

  function raiseGate(plane, step) {
    const r = S.runs[plane];
    const spec = gateSpec(plane, step, r);
    const version = (step._ver || 0) + 1; step._ver = version;
    const evidence = r.arts.slice(-3).map((a) => a.name).join(', ') || 'agent log';
    const id = `${r.id}-${spec.gate}-v${version}`;
    const hash = fnv(id + evidence + r.log.length);
    const ap = { id, plane, runId: r.id, step, gate: spec.gate, title: spec.title, scenario: r.sc.name, approvers: spec.approvers, signed: {}, status: 'pending', checks: spec.checks, evidence, hash, version, cls: spec.cls, raisedAt: now(), comment: '' };
    S.approvals.unshift(ap);
    r.status = 'waiting'; r.waitingFor = ap.id;
    log(plane, 'gate', 'Gate', `${spec.title} → waiting for ${spec.approvers.map((k) => DC.ROLES[k].title).join(' + ')}. Bound to hash ${hash}`);
    audit(step.agent, 'gate.request', `${ap.id} ${spec.title} hash=${hash}`);
    updateBadge();
    rerender();
    if (S.autoApprove) autoSign(ap);
  }

  function autoSign(ap) {
    let delay = 900 / S.speed;
    ap.approvers.forEach((role) => {
      setTimeout(() => { if (ap.status === 'pending') sign(ap.id, role, true); }, delay);
      delay += 700 / S.speed;
    });
  }

  function sign(apId, role, simulated) {
    const ap = S.approvals.find((a) => a.id === apId);
    if (!ap || ap.status !== 'pending' || ap.signed[role]) return;
    if (!ap.approvers.includes(role)) { toast(`${DC.ROLES[role].title} is not an approver for this gate.`); return; }
    ap.signed[role] = now();
    const person = DC.ROLES[role].person;
    log(ap.plane, 'human', `${person}`, `Signed ${ap.title} as ${DC.ROLES[role].title}${simulated ? ' (simulated approver)' : ''}`);
    audit(`${person} (${DC.ROLES[role].title})`, 'gate.sign', `${ap.id} hash=${ap.hash}`);
    if (ap.approvers.every((k) => ap.signed[k])) {
      ap.status = 'approved';
      ap.step._gateDone = true;
      const r = S.runs[ap.plane];
      log(ap.plane, 'ok', 'Gate', `${ap.title} approved by ${ap.approvers.length} of ${ap.approvers.length}. Continuing.`);
      audit('Runtime', 'gate.approved', ap.id);
      if (r && r.waitingFor === ap.id) { r.status = 'running'; r.gatesDone++; r.waitingFor = null; r.i++; r.li = 0; r.timer = setTimeout(() => tick(ap.plane), 350 / S.speed); }
      if (ap.onApprove) ap.onApprove();
    }
    updateBadge();
    rerender();
  }

  function decide(apId, decision, comment) {
    const ap = S.approvals.find((a) => a.id === apId);
    if (!ap || ap.status !== 'pending') return;
    const r = S.runs[ap.plane];
    ap.comment = comment || '';
    const actor = 'Reviewer';
    if (decision === 'reject') {
      ap.status = 'rejected';
      log(ap.plane, 'bad', actor, `Rejected ${ap.title}${comment ? ': ' + comment : ''}. Run stopped; nothing was deployed.`);
      audit(actor, 'gate.reject', `${ap.id} ${comment}`);
      if (r && r.waitingFor === ap.id) { r.status = 'rejected'; r.waitingFor = null; }
    } else {
      ap.status = 'changes';
      log(ap.plane, 'bad', actor, `Requested changes on ${ap.title}: ${comment || 'see review comment'}`);
      audit(actor, 'gate.changes', `${ap.id} ${comment}`);
      if (r && r.waitingFor === ap.id && r.revisions < 3) {
        r.revisions++;
        const step = ap.step;
        const agent = step.agent;
        r.status = 'running'; r.waitingFor = null;
        setTimeout(() => {
          log(ap.plane, 'agent', agent, `Revision ${step._ver + 1}: addressed reviewer comment "${comment || 'general'}". Re-ran checks; diff attached to the gate.`);
          raiseGate(ap.plane, step);
        }, 900 / S.speed);
      } else if (r && r.waitingFor === ap.id) {
        r.status = 'rejected';
        log(ap.plane, 'bad', 'Runtime', 'Return limit (3) reached. Escalated to the Data Product Owner.');
      }
    }
    updateBadge();
    rerender();
  }

  function finishRun(plane) {
    const r = S.runs[plane];
    r.status = 'done';
    log(plane, 'ok', 'Runtime', plane === 'build'
      ? `Delivered ${r.sc.product}: published to the internal marketplace and handed to Operate. ${r.gatesDone} human gates passed.`
      : `Incident closed. ${r.gatesDone} human decisions recorded.`);
    audit('Runtime', 'run.done', `${r.id}`);
    rerender();
  }

  /* ---------------- consume actions → approvals ---------------- */
  function raiseConsumeAction(ans) {
    const a = ans.action;
    const id = `C-${++S.seq}-ACTION`;
    const hash = fnv(id + a.title);
    const ap = { id, plane: 'consume', runId: 'C-' + S.seq, step: { agent: 'Next-Best-Action' }, gate: a.cls, title: a.title, scenario: ans.q, approvers: a.approvers.slice(), signed: {}, status: 'pending', checks: a.checks, evidence: a.value, hash, version: 1, cls: a.cls, raisedAt: now(), comment: '' };
    ap.onApprove = () => {
      S.chat.push({ type: 'sys', text: `Approved by ${ap.approvers.map((k) => DC.ROLES[k].person).join(' and ')}. Handed to the runtime for execution with the approved content and audience (hash ${hash}).` });
      if (S.view === 'consume') renderConsume();
    };
    S.approvals.unshift(ap);
    audit('Next-Best-Action', 'gate.request', `${id} ${a.title} hash=${hash}`);
    updateBadge();
    toast('Action sent for approval. See Approvals.');
    if (S.autoApprove) autoSign(ap);
    return ap;
  }

